-- Foco Platform - initial migration
-- PostgreSQL + Spring Boot 3 + Flyway

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(120) NOT NULL,
                       email VARCHAR(180) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       active BOOLEAN NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE user_preferences (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  user_id BIGINT NOT NULL UNIQUE,
                                  photo_url VARCHAR(1000),
                                  theme VARCHAR(15) NOT NULL DEFAULT 'SYSTEM',
                                  font_size VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
                                  compact_interface BOOLEAN NOT NULL DEFAULT FALSE,
                                  reduce_animations BOOLEAN NOT NULL DEFAULT FALSE,
                                  focus_duration_minutes INTEGER NOT NULL DEFAULT 25,
                                  break_duration_minutes INTEGER NOT NULL DEFAULT 5,
                                  notifications_enabled BOOLEAN NOT NULL DEFAULT TRUE,
                                  CONSTRAINT fk_user_preferences_user FOREIGN KEY (user_id) REFERENCES users(id),
                                  CONSTRAINT ck_user_preferences_theme CHECK (theme IN ('CLEAR', 'DARK', 'SYSTEM')),
                                  CONSTRAINT ck_user_preferences_focus_duration CHECK (focus_duration_minutes > 0),
                                  CONSTRAINT ck_user_preferences_break_duration CHECK (break_duration_minutes >= 0)
);

CREATE TABLE public_exams (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              user_id BIGINT NOT NULL,
                              name VARCHAR(180) NOT NULL,
                              organization VARCHAR(180),
                              exam_board VARCHAR(120),
                              exam_date DATE,
                              public_notice_url VARCHAR(1000),
                              status VARCHAR(30) NOT NULL DEFAULT 'IN_STUDY',
                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              CONSTRAINT fk_public_exams_user FOREIGN KEY (user_id) REFERENCES users(id),
                              CONSTRAINT ck_public_exams_status CHECK (status IN ('IN_STUDY', 'OPEN_ENROLLMENT', 'REALIZED', 'ARCHIVED'))
);

CREATE TABLE subjects (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          public_exam_id BIGINT NOT NULL,
                          name VARCHAR(160) NOT NULL,
                          weight NUMERIC(6,2),
                          display_order INTEGER NOT NULL DEFAULT 0,
                          status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
                          CONSTRAINT fk_subjects_public_exam FOREIGN KEY (public_exam_id) REFERENCES public_exams(id),
                          CONSTRAINT ck_subjects_weight CHECK (weight IS NULL OR weight >= 0)
);

CREATE TABLE topics (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        subject_id BIGINT NOT NULL,
                        parent_topic_id BIGINT,
                        name VARCHAR(180) NOT NULL,
                        description TEXT,
                        display_order INTEGER NOT NULL DEFAULT 0,
                        weight NUMERIC(6,2),
                        CONSTRAINT fk_topics_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
                        CONSTRAINT fk_topics_parent FOREIGN KEY (parent_topic_id) REFERENCES topics(id),
                        CONSTRAINT ck_topics_weight CHECK (weight IS NULL OR weight >= 0),
                        CONSTRAINT ck_topic_not_own_parent CHECK (parent_topic_id IS NULL OR parent_topic_id <> id)
);

CREATE TABLE study_plans (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             user_id BIGINT NOT NULL,
                             public_exam_id BIGINT,
                             name VARCHAR(180) NOT NULL,
                             weekly_goal_minutes INTEGER NOT NULL DEFAULT 0,
                             start_date DATE NOT NULL,
                             end_date DATE,
                             active BOOLEAN NOT NULL DEFAULT TRUE,
                             CONSTRAINT fk_study_plans_user FOREIGN KEY (user_id) REFERENCES users(id),
                             CONSTRAINT fk_study_plans_public_exam FOREIGN KEY (public_exam_id) REFERENCES public_exams(id),
                             CONSTRAINT ck_study_plans_weekly_goal CHECK (weekly_goal_minutes >= 0),
                             CONSTRAINT ck_study_plans_period CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE availabilities (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                study_plan_id BIGINT NOT NULL,
                                day_of_week SMALLINT NOT NULL,
                                start_time TIME NOT NULL,
                                end_time TIME NOT NULL,
                                CONSTRAINT fk_availabilities_study_plan FOREIGN KEY (study_plan_id) REFERENCES study_plans(id) ON DELETE CASCADE,
                                CONSTRAINT ck_availabilities_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
                                CONSTRAINT ck_availabilities_time_range CHECK (end_time > start_time)
);

CREATE TABLE study_tasks (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             study_plan_id BIGINT NOT NULL,
                             topic_id BIGINT NOT NULL,
                             title VARCHAR(180) NOT NULL,
                             type VARCHAR(20) NOT NULL DEFAULT 'THEORY',
                             planned_date DATE NOT NULL,
                             start_time TIME,
                             planned_duration_minutes INTEGER NOT NULL,
                             status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                             completed_at TIMESTAMPTZ,
                             notes TEXT,
                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT fk_study_tasks_study_plan FOREIGN KEY (study_plan_id) REFERENCES study_plans(id),
                             CONSTRAINT fk_study_tasks_topic FOREIGN KEY (topic_id) REFERENCES topics(id),
                             CONSTRAINT ck_study_tasks_type CHECK (type IN ('THEORY', 'REVIEW', 'READING', 'SUMMARY', 'OTHER')),
                             CONSTRAINT ck_study_tasks_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'CANCELED')),
                             CONSTRAINT ck_study_tasks_planned_duration CHECK (planned_duration_minutes > 0)
);

CREATE TABLE study_sessions (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                study_task_id BIGINT NOT NULL,
                                started_at TIMESTAMPTZ NOT NULL,
                                ended_at TIMESTAMPTZ,
                                duration_seconds BIGINT NOT NULL DEFAULT 0,
                                notes TEXT,
                                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                CONSTRAINT fk_study_sessions_study_task FOREIGN KEY (study_task_id) REFERENCES study_tasks(id),
                                CONSTRAINT ck_study_sessions_duration CHECK (duration_seconds >= 0),
                                CONSTRAINT ck_study_sessions_period CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE reviews (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         user_id BIGINT NOT NULL,
                         topic_id BIGINT NOT NULL,
                         source_session_id BIGINT,
                         scheduled_date DATE NOT NULL,
                         completed_at TIMESTAMPTZ,
                         result VARCHAR(15),
                         notes TEXT,
                         created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users(id),
                         CONSTRAINT fk_reviews_topic FOREIGN KEY (topic_id) REFERENCES topics(id),
                         CONSTRAINT fk_reviews_source_session FOREIGN KEY (source_session_id) REFERENCES study_sessions(id),
                         CONSTRAINT ck_reviews_result CHECK (result IS NULL OR result IN ('DIFFICULT', 'REASONABLE', 'EASY'))
);

CREATE TABLE goals (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       user_id BIGINT NOT NULL,
                       type VARCHAR(40) NOT NULL,
                       target_value INTEGER NOT NULL,
                       period_start DATE NOT NULL,
                       period_end DATE NOT NULL,
                       active BOOLEAN NOT NULL DEFAULT TRUE,
                       CONSTRAINT fk_goals_user FOREIGN KEY (user_id) REFERENCES users(id),
                       CONSTRAINT ck_goals_target_value CHECK (target_value > 0),
                       CONSTRAINT ck_goals_period CHECK (period_end >= period_start)
);

CREATE TABLE notifications (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               user_id BIGINT NOT NULL,
                               type VARCHAR(30) NOT NULL,
                               title VARCHAR(180) NOT NULL,
                               message TEXT NOT NULL,
                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               read_at TIMESTAMPTZ,
                               target_url VARCHAR(500),
                               CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users(id),
                               CONSTRAINT ck_notifications_type CHECK (type IN ('STUDY_REMINDER', 'PENDING_REVIEW', 'GOAL', 'COMPETITION_DEADLINE', 'SYSTEM'))
);

-- Indexes for relationships and frequent queries.
CREATE INDEX idx_public_exams_user ON public_exams(user_id);
CREATE INDEX idx_subjects_public_exam ON subjects(public_exam_id);
CREATE INDEX idx_topics_subject ON topics(subject_id);
CREATE INDEX idx_topics_parent ON topics(parent_topic_id);
CREATE INDEX idx_study_plans_user ON study_plans(user_id);
CREATE INDEX idx_study_plans_public_exam ON study_plans(public_exam_id);
CREATE INDEX idx_availabilities_study_plan ON availabilities(study_plan_id);
CREATE INDEX idx_study_tasks_plan_date_status ON study_tasks(study_plan_id, planned_date, status);
CREATE INDEX idx_study_tasks_topic ON study_tasks(topic_id);
CREATE INDEX idx_study_sessions_task ON study_sessions(study_task_id);
CREATE INDEX idx_study_sessions_started_at ON study_sessions(started_at);
CREATE INDEX idx_reviews_user_scheduled_date ON reviews(user_id, scheduled_date);
CREATE INDEX idx_reviews_topic ON reviews(topic_id);
CREATE INDEX idx_reviews_source_session ON reviews(source_session_id);
CREATE INDEX idx_goals_user_period ON goals(user_id, period_start, period_end);
CREATE INDEX idx_notifications_user_created_at ON notifications(user_id, created_at);
