-- Plataforma Foco - migration inicial
-- PostgreSQL + Spring Boot 3 + Flyway

CREATE TABLE usuarios (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nome VARCHAR(120) NOT NULL,
                          email VARCHAR(180) NOT NULL,
                          senha_hash VARCHAR(255) NOT NULL,
                          ativo BOOLEAN NOT NULL DEFAULT TRUE,
                          criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE preferencias_usuario (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      usuario_id BIGINT NOT NULL UNIQUE,
                                      foto_url VARCHAR(1000),
                                      tema VARCHAR(15) NOT NULL DEFAULT 'SISTEMA',
                                      tamanho_fonte VARCHAR(20) NOT NULL DEFAULT 'MEDIO',
                                      interface_compacta BOOLEAN NOT NULL DEFAULT FALSE,
                                      reduzir_animacoes BOOLEAN NOT NULL DEFAULT FALSE,
                                      duracao_foco_minutos INTEGER NOT NULL DEFAULT 25,
                                      duracao_pausa_minutos INTEGER NOT NULL DEFAULT 5,
                                      notificacoes_ativas BOOLEAN NOT NULL DEFAULT TRUE,
                                      CONSTRAINT fk_preferencias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
                                      CONSTRAINT ck_preferencias_tema CHECK (tema IN ('CLARO', 'ESCURO', 'SISTEMA')),
                                      CONSTRAINT ck_preferencias_foco CHECK (duracao_foco_minutos > 0),
                                      CONSTRAINT ck_preferencias_pausa CHECK (duracao_pausa_minutos >= 0)
);

CREATE TABLE concursos (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           usuario_id BIGINT NOT NULL,
                           nome VARCHAR(180) NOT NULL,
                           orgao VARCHAR(180),
                           banca VARCHAR(120),
                           data_prova DATE,
                           edital_url VARCHAR(1000),
                           status VARCHAR(30) NOT NULL DEFAULT 'EM_ESTUDO',
                           criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           CONSTRAINT fk_concursos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
                           CONSTRAINT ck_concursos_status CHECK (status IN ('EM_ESTUDO', 'INSCRICAO_ABERTA', 'REALIZADO', 'ARQUIVADO'))
);

CREATE TABLE disciplinas (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             concurso_id BIGINT NOT NULL,
                             nome VARCHAR(160) NOT NULL,
                             peso NUMERIC(6,2),
                             ordem INTEGER NOT NULL DEFAULT 0,
                             status VARCHAR(30) NOT NULL DEFAULT 'ATIVA',
                             CONSTRAINT fk_disciplinas_concurso FOREIGN KEY (concurso_id) REFERENCES concursos(id),
                             CONSTRAINT ck_disciplinas_peso CHECK (peso IS NULL OR peso >= 0)
);

CREATE TABLE topicos (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         disciplina_id BIGINT NOT NULL,
                         topico_pai_id BIGINT,
                         nome VARCHAR(180) NOT NULL,
                         descricao TEXT,
                         ordem INTEGER NOT NULL DEFAULT 0,
                         peso NUMERIC(6,2),
                         CONSTRAINT fk_topicos_disciplina FOREIGN KEY (disciplina_id) REFERENCES disciplinas(id),
                         CONSTRAINT fk_topicos_pai FOREIGN KEY (topico_pai_id) REFERENCES topicos(id),
                         CONSTRAINT ck_topicos_peso CHECK (peso IS NULL OR peso >= 0),
                         CONSTRAINT ck_topico_nao_e_pai_de_si CHECK (topico_pai_id IS NULL OR topico_pai_id <> id)
);

CREATE TABLE planos_estudo (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               usuario_id BIGINT NOT NULL,
                               concurso_id BIGINT,
                               nome VARCHAR(180) NOT NULL,
                               meta_semanal_minutos INTEGER NOT NULL DEFAULT 0,
                               data_inicio DATE NOT NULL,
                               data_fim DATE,
                               ativo BOOLEAN NOT NULL DEFAULT TRUE,
                               CONSTRAINT fk_planos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
                               CONSTRAINT fk_planos_concurso FOREIGN KEY (concurso_id) REFERENCES concursos(id),
                               CONSTRAINT ck_planos_meta CHECK (meta_semanal_minutos >= 0),
                               CONSTRAINT ck_planos_periodo CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE TABLE disponibilidades (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  plano_id BIGINT NOT NULL,
                                  dia_semana SMALLINT NOT NULL,
                                  hora_inicio TIME NOT NULL,
                                  hora_fim TIME NOT NULL,
                                  CONSTRAINT fk_disponibilidades_plano FOREIGN KEY (plano_id) REFERENCES planos_estudo(id) ON DELETE CASCADE,
                                  CONSTRAINT ck_disponibilidade_dia CHECK (dia_semana BETWEEN 1 AND 7),
                                  CONSTRAINT ck_disponibilidade_horario CHECK (hora_fim > hora_inicio)
);

CREATE TABLE tarefas_estudo (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                plano_id BIGINT NOT NULL,
                                topico_id BIGINT NOT NULL,
                                titulo VARCHAR(180) NOT NULL,
                                tipo VARCHAR(20) NOT NULL DEFAULT 'TEORIA',
                                data_planejada DATE NOT NULL,
                                hora_inicio TIME,
                                duracao_planejada_minutos INTEGER NOT NULL,
                                status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
                                concluida_em TIMESTAMPTZ,
                                observacoes TEXT,
                                criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                CONSTRAINT fk_tarefas_plano FOREIGN KEY (plano_id) REFERENCES planos_estudo(id),
                                CONSTRAINT fk_tarefas_topico FOREIGN KEY (topico_id) REFERENCES topicos(id),
                                CONSTRAINT ck_tarefas_tipo CHECK (tipo IN ('TEORIA', 'REVISAO', 'LEITURA', 'RESUMO', 'OUTRO')),
                                CONSTRAINT ck_tarefas_status CHECK (status IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')),
                                CONSTRAINT ck_tarefas_duracao CHECK (duracao_planejada_minutos > 0)
);

CREATE TABLE sessoes_estudo (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                tarefa_id BIGINT NOT NULL,
                                inicio_em TIMESTAMPTZ NOT NULL,
                                fim_em TIMESTAMPTZ,
                                duracao_segundos BIGINT NOT NULL DEFAULT 0,
                                observacoes TEXT,
                                criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                CONSTRAINT fk_sessoes_tarefa FOREIGN KEY (tarefa_id) REFERENCES tarefas_estudo(id),
                                CONSTRAINT ck_sessoes_duracao CHECK (duracao_segundos >= 0),
                                CONSTRAINT ck_sessoes_periodo CHECK (fim_em IS NULL OR fim_em >= inicio_em)
);

CREATE TABLE revisoes (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          usuario_id BIGINT NOT NULL,
                          topico_id BIGINT NOT NULL,
                          sessao_origem_id BIGINT,
                          data_prevista DATE NOT NULL,
                          data_realizada TIMESTAMPTZ,
                          resultado VARCHAR(15),
                          observacoes TEXT,
                          criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          CONSTRAINT fk_revisoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
                          CONSTRAINT fk_revisoes_topico FOREIGN KEY (topico_id) REFERENCES topicos(id),
                          CONSTRAINT fk_revisoes_sessao FOREIGN KEY (sessao_origem_id) REFERENCES sessoes_estudo(id),
                          CONSTRAINT ck_revisoes_resultado CHECK (resultado IS NULL OR resultado IN ('DIFICIL', 'RAZOAVEL', 'FACIL'))
);

CREATE TABLE metas (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       usuario_id BIGINT NOT NULL,
                       tipo VARCHAR(40) NOT NULL,
                       valor_objetivo INTEGER NOT NULL,
                       periodo_inicio DATE NOT NULL,
                       periodo_fim DATE NOT NULL,
                       ativa BOOLEAN NOT NULL DEFAULT TRUE,
                       CONSTRAINT fk_metas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
                       CONSTRAINT ck_metas_valor CHECK (valor_objetivo > 0),
                       CONSTRAINT ck_metas_periodo CHECK (periodo_fim >= periodo_inicio)
);

CREATE TABLE notificacoes (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              usuario_id BIGINT NOT NULL,
                              tipo VARCHAR(30) NOT NULL,
                              titulo VARCHAR(180) NOT NULL,
                              mensagem TEXT NOT NULL,
                              criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              lida_em TIMESTAMPTZ,
                              link_destino VARCHAR(500),
                              CONSTRAINT fk_notificacoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
                              CONSTRAINT ck_notificacoes_tipo CHECK (tipo IN ('LEMBRETE_ESTUDO', 'REVISAO_PENDENTE', 'META', 'PRAZO_CONCURSO', 'SISTEMA'))
);

-- Índices para relacionamentos e consultas frequentes.
CREATE INDEX idx_concursos_usuario ON concursos(usuario_id);
CREATE INDEX idx_disciplinas_concurso ON disciplinas(concurso_id);
CREATE INDEX idx_topicos_disciplina ON topicos(disciplina_id);
CREATE INDEX idx_topicos_pai ON topicos(topico_pai_id);
CREATE INDEX idx_planos_usuario ON planos_estudo(usuario_id);
CREATE INDEX idx_planos_concurso ON planos_estudo(concurso_id);
CREATE INDEX idx_disponibilidades_plano ON disponibilidades(plano_id);
CREATE INDEX idx_tarefas_plano_data_status ON tarefas_estudo(plano_id, data_planejada, status);
CREATE INDEX idx_tarefas_topico ON tarefas_estudo(topico_id);
CREATE INDEX idx_sessoes_tarefa ON sessoes_estudo(tarefa_id);
CREATE INDEX idx_sessoes_inicio ON sessoes_estudo(inicio_em);
CREATE INDEX idx_revisoes_usuario_data ON revisoes(usuario_id, data_prevista);
CREATE INDEX idx_revisoes_topico ON revisoes(topico_id);
CREATE INDEX idx_revisoes_sessao ON revisoes(sessao_origem_id);
CREATE INDEX idx_metas_usuario_periodo ON metas(usuario_id, periodo_inicio, periodo_fim);
CREATE INDEX idx_notificacoes_usuario_criada ON notificacoes(usuario_id, criada_em);
